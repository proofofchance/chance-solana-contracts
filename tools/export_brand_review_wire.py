#!/usr/bin/env python3
"""Generate pure typed Rust readers from the canonical V1 brand-review IDL."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def ty(value):
    if isinstance(value, str): return {"pubkey":"String", "string":"String", "bytes":"Vec<u8>"}.get(value, value)
    if "defined" in value: return value["defined"]["name"]
    if "vec" in value: return f'Vec<{ty(value["vec"])}>'
    return f'[{ty(value["array"][0])}; {value["array"][1]}]'
def result(value):
    if isinstance(value,str): return f'r.{value}()'
    if "defined" in value: return f'{value["defined"]["name"]}::decode(r)'
    if "vec" in value: return '{ let count = r.length()?; (0..count).map(|_| '+result(value["vec"])+').collect::<Result<Vec<_>>>() }'
    item,n=value["array"]
    return '{ (0..'+str(n)+').map(|_| '+result(item)+').collect::<Result<Vec<_>>>()?.try_into().map_err(|_| anyhow::anyhow!("array width")) }'
def read(value):
    return result(value)+'?'
def generate():
    schema=json.loads((ROOT/'audit/schemas/giveaways-brand-review-v1.idl.json').read_text())
    out='// Generated by tools/export_brand_review_wire.py from the canonical IDL.\nuse super::{Reader, WireRecord};\nuse anyhow::Result;\n'
    for item in schema['types']:
        name=item['name'];fields=item['type']['fields']
        out+='#[derive(Debug, Clone, PartialEq, Eq)]\npub struct '+name+' {\n'
        for field in fields: out+='    pub '+field['name']+': '+ty(field['type'])+',\n'
        out+='}\nimpl WireRecord for '+name+' {\n'
        account=next((v for v in schema['accounts'] if v['name']==name),None)
        if account: out+='    const DISCRIMINATOR: Option<[u8; 8]> = Some('+str(account['discriminator'])+');\n'
        out+='    fn decode(r: &mut Reader) -> Result<Self> {\n        Ok(Self {\n'
        for field in fields: out+='            '+field['name']+': '+read(field['type'])+',\n'
        out+='        })\n    }\n}\n'
    event=next(v for v in schema['events'] if v['name']=='BrandReviewRecord')
    out+='pub const RECORD_DISCRIMINATOR: [u8; 8] = '+str(event['discriminator'])+';\n'
    return out
if __name__ == '__main__':
    parser=argparse.ArgumentParser(description=__doc__); parser.add_argument('--output',type=Path,required=True);args=parser.parse_args()
    args.output.write_text(generate())
